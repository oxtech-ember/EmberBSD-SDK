"""Qualify a Darwin package for installation into another SDK prefix.

Whole packages only. Text relocation and deferred hooks are explicit;
retaining binary build paths requires a relocated runtime check.
"""
import argparse
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
from emberbsd_sdk.bootstrap_bundle import unpack_package, make_relative, _replace_file, text_references
from emberbsd_sdk import package_relocation
from emberbsd_sdk.errors import SDKError
from emberbsd_sdk.host_prefix import load_host_prefix
from emberbsd_sdk.package_install import PORTABLE_PREFIX
from emberbsd_sdk.release_signing import ReleaseCrypto, read_bytes


def dependency_files(crypto, prefix, patterns):
    """Inspect pkg_tools' installed closure; do not solve or install versions."""
    pending, selected, seen, files = list(patterns), set(), set(), set()
    database = Path(prefix) / 'pkgdb'
    while pending:
        pattern = pending.pop()
        if pattern in seen:
            continue
        seen.add(pattern)
        names = crypto.run_package('pkg_info', ['-K', database, '-e', pattern]).decode().splitlines()
        if len(names) != 1 or Path(names[0]).name != names[0]:
            raise SDKError('dependency must select one installed provider: ' + pattern)
        name = names[0]
        if name in selected:
            continue
        selected.add(name)
        lines = (database / name / '+CONTENTS').read_text().splitlines()
        files.update(line for line in lines if line and not line.startswith(('@', '+')))
        pending.extend(line[8:] for line in lines if line.startswith('@pkgdep '))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--host-prefix', required=True)
    parser.add_argument('--dependency-prefix', type=Path, required=True)
    parser.add_argument('--bootstrap-install-name-tool', type=Path, required=True)
    parser.add_argument('--codesign', type=Path, required=True)
    parser.add_argument('--relocate-text', action='store_true',
        help='declare first-install relocation for text files and library-provider metadata')
    parser.add_argument('--allow-binary-prefix', action='store_true',
        help='retain binary build-path strings; requires relocation testing by the producer')
    parser.add_argument('--package-revision', metavar='N',
        help='increase the pkgsrc nb revision after the matching Ports recipe bump')
    parser.add_argument('--install-script', type=Path,
        help='replace +INSTALL with a script generated by the current Ports recipe')
    parser.add_argument('--deinstall-script', type=Path,
        help='replace +DEINSTALL with a script generated by the current Ports recipe')
    parser.add_argument('--defer-hooks', action='store_true',
        help='qualify repeatable hooks that run after extraction and text relocation')
    args = parser.parse_args()
    try:
        if platform.system() != 'Darwin' or args.output.exists():
            raise SDKError('select a new output on a Darwin producer')
        if args.allow_binary_prefix and not args.relocate_text:
            raise SDKError('--allow-binary-prefix requires --relocate-text')
        if args.defer_hooks and not args.relocate_text:
            raise SDKError('--defer-hooks requires --relocate-text')
        if (args.install_script or args.deinstall_script) and not (args.package_revision and args.defer_hooks):
            raise SDKError('replacement scripts require --package-revision and --defer-hooks')
        for tool in (args.bootstrap_install_name_tool, args.codesign):
            if not tool.is_absolute() or not tool.is_file():
                raise SDKError('select explicit absolute packaging tools')
        crypto = ReleaseCrypto(load_host_prefix(args.host_prefix, required_roles=('pkg_create', 'pkg_admin', 'pkg_info')))
        with tempfile.TemporaryDirectory(prefix='ember-portable-') as directory:
            root = Path(directory) / 'payload'
            root.mkdir()
            name, prefix = unpack_package(args.package, root)
            database = root / 'pkgdb' / name
            new_name = name
            if args.package_revision is not None:
                revision = args.package_revision
                if re.fullmatch(r'[1-9][0-9]*', revision) is None:
                    raise SDKError('package revision must be a positive decimal integer')
                match = re.fullmatch(r'(.+-[0-9][A-Za-z0-9._+]*?)(?:nb([0-9]+))?', name)
                if match is None or int(revision) <= int(match.group(2) or '0'):
                    raise SDKError('package revision must increase the existing nb revision')
                new_name = match.group(1) + 'nb' + revision
            if not args.defer_hooks and any((database / script).exists() for script in ('+INSTALL', '+DEINSTALL')):
                raise SDKError('package has installation scripts')
            lines = (database / '+CONTENTS').read_text().splitlines()
            # An already qualified producer package can be repacked without
            # compiling its payload. Replace its declaration, do not duplicate it.
            package_relocation.declaration(lines)
            lines = [line for line in lines if line not in
                     (package_relocation.MARKER, package_relocation.HOOKS, PORTABLE_PREFIX)
                     and not line.startswith((package_relocation.SOURCE, package_relocation.TEXT))]
            for member, source in (('+INSTALL', args.install_script), ('+DEINSTALL', args.deinstall_script)):
                if source is not None:
                    destination = database / member
                    content = read_bytes(source, 8 * 1024 * 1024)
                    if destination.is_symlink() or (destination.exists() and not destination.is_file()):
                        raise SDKError('package hook metadata is not a regular file: ' + member)
                    if destination.exists():
                        _replace_file(destination, content)
                    else:
                        destination.write_bytes(content)
                    destination.chmod(0o755)
            if any(line.startswith(('@exec ', '@unexec ')) for line in lines):
                raise SDKError('package has installation commands')
            # pkg_add's REQUIRES check uses absolute paths, even with -p.
            # Replace qualified prefix-local library requirements with the
            # existing pkgdep contracts; keep all system requirements intact.
            dependencies = [line[8:] for line in lines if line.startswith('@pkgdep ')]
            providers = dependency_files(crypto, args.dependency_prefix, dependencies)
            make_relative(root, prefix, dict(os='Darwin', cpu=platform.machine()),
                          args.bootstrap_install_name_tool, args.codesign,
                          dependency_root=args.dependency_prefix, dependency_files=providers)
            info = database / '+BUILD_INFO'
            updated = []
            for line in info.read_text().splitlines():
                if args.package_revision is not None and line.split('=', 1)[0] in (
                        'PKGNAME', 'PKGVERSION', 'PKGREVISION'):
                    raise SDKError('package build metadata contains a package identity field')
                if line.startswith('PROVIDES=') and prefix + '/' in line and not args.relocate_text:
                    raise SDKError('portable library providers require package-owner relocation support')
                if line.startswith('REQUIRES='):
                    required = []
                    for value in line[9:].split():
                        if value.startswith(prefix + '/'):
                            relative = value[len(prefix) + 1:]
                            supplied = root / relative
                            owner = root
                            if not supplied.is_file() and relative in providers:
                                supplied = args.dependency_prefix / relative
                                owner = args.dependency_prefix
                            if not supplied.is_file() or not supplied.resolve().is_relative_to(owner.resolve()):
                                raise SDKError('local library has no declared package dependency: ' + relative)
                        elif value.startswith(('/usr/lib/', '/System/Library/')):
                            required.append(value)
                        else:
                            raise SDKError('external package requirement: ' + value)
                    if not required:
                        continue
                    line = 'REQUIRES=' + ' '.join(required)
                updated.append(line)
            _replace_file(info, ('\n'.join(updated) + '\n').encode())
            texts = [relative for relative in text_references(root, prefix, [name])
                     if not relative.startswith('pkgdb/')]
            for path in root.rglob('*'):
                if path.is_file() and not path.is_symlink() and not path.is_relative_to(root / 'pkgdb'):
                    if args.relocate_text and path.relative_to(root).as_posix() in texts:
                        continue
                    # Only a producer check; clients trust the signed qualification.
                    with path.open('rb') as source:
                        tail = b''
                        while chunk := source.read(1024 * 1024):
                            chunk = tail + chunk
                            if prefix.encode() in chunk:
                                source.seek(0)
                                if not args.allow_binary_prefix or b'\0' not in source.read(8192):
                                    raise SDKError('payload still embeds its producer prefix: ' + str(path.relative_to(root)))
                                break
                            tail = chunk[-len(prefix):]
            packing = ([package_relocation.MARKER, package_relocation.SOURCE + prefix,
                        *[package_relocation.TEXT + name for name in texts]]
                       if args.relocate_text else [PORTABLE_PREFIX])
            if args.defer_hooks:
                packing.append(package_relocation.HOOKS)
            ignored = False
            for line in lines:
                if args.package_revision is not None and line.startswith('@name '):
                    if line != '@name ' + name:
                        raise SDKError('package has inconsistent names')
                    line = '@name ' + new_name
                if ignored:
                    ignored = False
                elif line == '@ignore':
                    ignored = True
                elif not line.startswith(('@cwd ', '@comment MD5:', '@comment Symlink:')):
                    packing.append(line)
            plist = Path(directory) / 'PLIST'
            plist.write_text('\n'.join(packing) + '\n')
            command = ['-F', 'gzip', '-f', plist, '-p', root, '-I', prefix]
            for flag, member in (('-c', '+COMMENT'), ('-d', '+DESC'), ('-B', '+BUILD_INFO'),
                                 ('-b', '+BUILD_VERSION'), ('-s', '+SIZE_PKG'), ('-S', '+SIZE_ALL'),
                                 ('-n', '+PRESERVE'), ('-D', '+DISPLAY')):
                if (database / member).exists():
                    command += [flag, database / member]
            if args.defer_hooks:
                for flag, member in (('-i', '+INSTALL'), ('-k', '+DEINSTALL')):
                    if (database / member).exists():
                        command += [flag, database / member]
            crypto.run_package('pkg_create', [*command, args.output.absolute()])
        print(args.output)
        return 0
    except (SDKError, OSError, ValueError, subprocess.CalledProcessError) as exc:
        print('package-portable: ' + str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
