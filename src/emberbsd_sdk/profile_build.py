"""Build a profile: generate build.ninja from its plan and run each node.

The plan decides what to build. Ninja decides the order and runs the edges.
The producer of a node decides how: a Ports source producer prepares a
source, ember/build-kernel.sh builds the tools and a kernel. Each edge
writes the record of its node (results/<id>.json) after its producer
succeeds. The input key is in the command line of the edge, so Ninja runs an
edge again when the key changes. A node without a key (local changes) depends
on a phony target without outputs, so Ninja runs it on each build; the
incremental builder of its owner then skips unchanged work.
"""

import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

from . import build_profile, jobserver, process
from .errors import SDKError
from .jsonio import read_json, write_json

NINJA_FILE = 'build.ninja'
PLAN_FILE = 'plan.json'
# The OS producers. The tools build runs inside its consumer.
KERNEL_BUILDER = 'ember/build-kernel.sh'
# The Prebuild SDK workspace of profile-build, inside its work directory.
WORKSPACE = 'sdk'
# The host and target tools that the OS objects of a release depend on.
RUNTIME_NODES = ('runtime:host-prefix', 'runtime:target-toolchain', 'runtime:host-binutils')


def _require(condition, message):
    if not condition:
        raise SDKError(message)


def _escape(path):
    """Escape a path for a Ninja build line."""
    return str(path).replace('$', '$$').replace(' ', '$ ').replace(':', '$:')


def record_name(node_id):
    return os.path.relpath(build_profile.result_path('/', node_id), '/')


def runnable(node):
    """Return why profile-build cannot run NODE, or None."""
    if node['kind'] == 'source':
        producer = node['identity']['producer']
        repository, path = producer.split(':', 1)
        if not (repository == 'ports' and path.startswith('scripts/source-inputs/')) and producer != build_profile.LIBEDIT:
            return f'select the prepared tree in build.sources; {producer} has no common producer interface'
    elif node['kind'] == 'os-stage' and node['identity'].get('stage') not in ('tools', 'kernel', 'sets'):
        return f'profile-build cannot build the OS stage {node["identity"].get("stage")}'
    elif node['identity'].get('stage') == 'sets' and node['input_key'] is None:
        return 'commit the OS, Ports and SDK changes first: the OS release builder needs clean checkouts'
    return None


def ninja_file(plan, *, command):
    """Return build.ninja for the nodes of PLAN that are not ready.

    COMMAND is the argument list that runs one node."""
    nodes = {node['id']: node for node in plan['nodes']}
    # Quote for the shell, then for Ninja. IDs and keys need no quotes.
    command = ' '.join(shlex.quote(str(word)) for word in command).replace('$', '$$')
    lines = ['# Generated by the EmberBSD SDK from the build plan. Do not edit.',
             'ninja_required_version = 1.10', '',
             '# OS stages run build.sh, which runs its own jobs.',
             'pool os', '  depth = 1', '',
             'rule node', f'  command = {command} --node $id --key $key', '  description = $id', '',
             '# A node with local changes depends on this target, which never exists.',
             'build changed: phony', '']
    for node in plan['nodes']:
        if node['decision']['action'] == 'ready':
            continue
        _require(node['decision']['action'] == 'build',
                 f'{node["id"]}: {node["decision"]["action"]} first ({node["decision"]["why"]})')
        reason = runnable(node)
        _require(reason is None, f'{node["id"]}: {reason}')
        # Ready dependencies are already complete; order only the edges of this build.
        inputs = [_escape(record_name(item)) for item in node['dependencies']
                  if nodes[item]['decision']['action'] != 'ready']
        line = f'build {_escape(record_name(node["id"]))}: node'
        if node['input_key'] is None:
            line += ' | changed'
        if inputs:
            line += ' || ' + ' '.join(inputs)
        lines += [line, f'  id = {node["id"]}', f'  key = {node["input_key"] or "changed"}']
        if node['kind'] == 'os-stage':
            lines.append('  pool = os')
        lines.append('')
    return '\n'.join(lines)


def _record(work, node_id):
    path = Path(work, record_name(node_id))
    record = read_json(path) if path.is_file() else None
    _require(isinstance(record, dict) and isinstance(record.get('outputs'), dict),
             f'{node_id} has no result record')
    return record


def _run(argv, env=None):
    # Ninja shows the output of a failed edge.
    if subprocess.run(argv, env=env, check=False).returncode != 0:
        raise SDKError('producer failed: ' + ' '.join(argv[:3]))


def _write_record(work, node, outputs):
    path = Path(work, record_name(node['id']))
    path.parent.mkdir(parents=True, exist_ok=True)
    write_json(path, dict(id=node['id'], input_key=node['input_key'], outputs=outputs), exclusive=False)


def _source_path(work, config, variable):
    selected = config['selected_sources'].get(variable)
    return selected or _record(work, 'source:' + variable)['outputs'][variable]


def run_node(work, node_id, key, config):
    """Run the producer of NODE_ID from the plan in WORK and write its record."""
    plan = read_json(Path(work, PLAN_FILE))
    nodes = {node['id']: node for node in plan['nodes']}
    _require(node_id in nodes, f'the plan has no node {node_id}')
    node = nodes[node_id]
    _require((node['input_key'] or 'changed') == key, f'{node_id}: the plan changed; run profile-build again')
    # The plan keys the export with the gpatch of the resolved host prefix.
    prefix = os.path.realpath(config['host_prefix'])
    # A producer can remove the outputs of an earlier result, so that result is
    # no longer valid. Remove its record before the producer starts.
    Path(work, record_name(node_id)).unlink(missing_ok=True)
    gpatch = os.path.join(prefix, 'bin/gpatch')
    git = shutil.which('git')
    _require(git is not None and os.path.isabs(git), 'install Git on the host')
    if node['kind'] == 'source':
        identity = node['identity']
        _require(runnable(node) is None and re.fullmatch(r'EMBER_[A-Z0-9_]+_SOURCE', identity['variable']),
                 f'{node_id}: {runnable(node)}')
        output = Path(work, 'sources', f'{identity["variable"]}-{(node["input_key"] or "changed")[:16]}')
        if output.exists():
            # A failed or interrupted preparation leaves no record; start again.
            shutil.rmtree(output)
        output.parent.mkdir(parents=True, exist_ok=True)
        if identity['producer'] == build_profile.LIBEDIT:
            from .libedit import prepare_source
            _require(len(identity['distfiles']) == 1, f'{node_id}: the libedit recipe must name one distfile')
            prepare_source(config['ports_root'], os.path.join(config['distfiles'], identity['distfiles'][0]),
                           str(output), patch_tool=gpatch)
        else:
            path = Path(config['ports_root'], identity['producer'].split(':', 1)[1])
            export = _record(work, build_profile.EXPORT_NODE)['outputs']['pkgsrc-export']
            argv = [sys.executable, '-B', str(path / 'source.py' if path.is_dir() else path),
                    '--sdk-source', config['sdk_root'], '--git', git, 'prepare', '--output', str(output),
                    '--patch', gpatch, '--pkgsrc-export', export, '--export-patch', gpatch]
            if identity['distfiles']:
                argv += ['--distdir', config['distfiles']]
            # A producer is one job; it does not take part in the jobserver.
            env = {name: value for name, value in os.environ.items() if name not in ('MAKEFLAGS', 'MFLAGS')}
            _run(argv, env=env)
        _write_record(work, node, {identity['variable']: str(output)})
    elif node['kind'] == 'export':
        # The export stage keeps one export per fingerprint in the workspace.
        root = Path(_workspace(work, plan), 'stages', 'pkgsrc-export')
        root.mkdir(parents=True, exist_ok=True)
        data = subprocess.run([sys.executable, '-B', os.path.join(config['ports_root'], build_profile.EXPORT_TOOL),
                               'prepare', str(root), '--sdk-source', config['sdk_root'], '--git', git,
                               '--patch', gpatch], stdout=subprocess.PIPE, check=False,
                              env=process.sanitized_environment())
        _require(data.returncode == 0, 'producer failed: ' + build_profile.EXPORT_TOOL)
        try:
            result = json.loads(data.stdout)
        except ValueError as exc:
            raise SDKError(f'{build_profile.EXPORT_TOOL} printed no JSON result') from exc
        _require(result.get('fingerprint') == node['inputs']['fingerprint'],
                 f'{node_id}: the Ports export inputs changed; run profile-build again')
        _write_record(work, node, {'pkgsrc-export': result['directory']})
    elif node_id == 'os:tools':
        # build.sh of each consumer builds or reuses the tools in its object tree.
        _write_record(work, node, {})
    elif node['identity'].get('stage') == 'kernel':
        config_name = node['identity']['config']
        out = Path(work, 'kernels')
        env = process.sanitized_environment()
        env.pop('MAKECONF', None)
        env.update(EMBERBSD_SDK_SOURCE=config['sdk_root'], EMBER_HOST_PREFIX=prefix,
                   EMBER_HOST_COMPILER_FAMILY=plan['profile']['platform']['compiler']['host'],
                   EMBER_COMPILER_FAMILY=plan['profile']['platform']['compiler']['target'],
                   EMBER_BUILD_MODE='cross', EMBER_EXTERNAL_TOOLCHAIN=prefix,
                   EMBER_HOST_BFD_CONFIG=config['host_bfd_config'],
                   MKREPRO_TIMESTAMP=str(node['inputs']['repro_timestamp']))
        if plan['profile']['os']['buildinfo']:
            env['BUILDINFO'] = plan['profile']['os']['buildinfo']
        sources = [item for item in nodes['os:tools']['dependencies'] + node['dependencies']
                   if item.startswith('source:')]
        for item in sorted(set(sources)):
            variable = item.split(':', 1)[1]
            env[variable] = _source_path(work, config, variable)
        out.mkdir(parents=True, exist_ok=True)
        # bmake has its own job pool: take the free jobserver tokens for it.
        with jobserver.slots(os.environ.get('MAKEFLAGS'), config['jobs']) as jobs:
            env['NETBSD2_JOBS'] = str(jobs)
            _run([os.path.join(prefix, 'bin/mksh'), os.path.join(config['os_source'], KERNEL_BUILDER),
                  str(out), config_name], env=env)
        _write_record(work, node, {name: str(out / name) for name in node['outputs']})
    elif node['identity'].get('stage') == 'sets':
        _write_record(work, node, _release(work, node, nodes, plan, config, prefix))
    else:
        raise SDKError(f'{node_id}: {runnable(node)}')
    return 0


def _workspace(work, plan, create=False):
    """Return the Prebuild SDK workspace of WORK. CREATE makes it for the profile target."""
    from . import workspace
    root, target = Path(work, WORKSPACE), plan['profile']['platform']['target']
    if create and not root.exists():
        workspace.create(str(root), target=target)
    try:
        layout = workspace.inspect_layout(str(root))
        workspace.require_target(layout, target)
    except SDKError as exc:
        raise SDKError(f'{root} is not a Prebuild SDK workspace for {target} ({exc}); remove it') from exc
    return layout['canonical_root']


def _source_option(variable):
    """Return the builder option of VARIABLE: EMBER_TCP_WRAPPERS_SOURCE is tcp-wrappers-source."""
    return variable.removeprefix('EMBER_').lower().replace('_', '-')


def _source_content(path):
    """Return the sha256 of the manifest at the root of a prepared source tree."""
    for name in ('emberbsd-prepared-source.json', 'libedit-source.json', 'llvm-source.json'):
        manifest = Path(path, name)
        if manifest.is_file():
            return hashlib.sha256(manifest.read_bytes()).hexdigest()
    raise SDKError(f'{path} has no prepared source manifest')


def _release(work, node, nodes, plan, config, prefix):
    """Build the sets of NODE with the OS release builder; return the set files."""
    from .os_release_builder import OSReleaseBuilder
    from .sysroot_builder import SOURCE_OPTIONS

    class Release(OSReleaseBuilder):
        # A development build restarts the SDK-named LLVM stages that an
        # interrupted run left, as build-sysroot.py does.
        RESUMES_FAILED_STAGES = True

    _require(runnable(node) is None, f'{node["id"]}: {runnable(node)}')
    root = _workspace(work, plan)
    platform = plan['profile']['platform']
    destination = Path(root, 'stages', f'os-sets-{node["input_key"][:16]}')
    if destination.exists():
        # A failed or interrupted release leaves no record; start again.
        shutil.rmtree(destination)
    # A new workspace has no stages directory yet.
    destination.parent.mkdir(exist_ok=True)
    sources = {}
    for item in sorted(set(nodes['os:tools']['dependencies'] + node['dependencies'])):
        if item.startswith('source:'):
            variable = item.split(':', 1)[1]
            # EMBER_TCP_WRAPPERS_SOURCE is the builder option tcp-wrappers-source.
            _require(_source_option(variable) in (*SOURCE_OPTIONS, 'llvm-source', 'libedit-source'),
                     f'{node["id"]}: the OS release builder does not read {variable}')
            sources[variable] = _source_path(work, config, variable)
    # The builder reuses objects, tools, LLVM stages and the LLVM runtime only
    # for the same host and target tools and the same prepared sources: it
    # compares their paths and whole manifests. Other inputs get other
    # directories.
    material = [nodes[item]['input_key'] for item in RUNTIME_NODES]
    material += [f'{variable}={path}={_source_content(path)}' for variable, path in sorted(sources.items())]
    tools_key = hashlib.sha256('\n'.join(material).encode()).hexdigest()[:16]
    options = {'sdk': root, 'os': config['os_source'], 'ports': config['ports_root'], 'compiler': prefix,
               'sdk-source': config['sdk_root'], 'host-prefix': prefix,
               'host-binutils': os.path.dirname(config['host_bfd_config']),
               'runtime-work': os.path.join(root, 'obj', f'llvm-runtime-{tools_key}'),
               'llvm-stage-root': os.path.join(root, 'stages', f'llvm-{tools_key}'),
               'destination': str(destination),
               'objects': os.path.join(root, 'obj', f'os-{tools_key}'),
               'tools': os.path.join(root, 'obj', f'tools-{tools_key}'),
               'llvm-objects': os.path.join(root, 'obj', f'llvm-{tools_key}'),
               'distdir': config['distfiles'], 'target': platform['target'],
               'compiler-family': platform['compiler']['target'],
               'host-compiler-family': platform['compiler']['host']}
    for variable, path in sources.items():
        options[_source_option(variable)] = path
    # bmake has its own job pool: take the free jobserver tokens for it.
    with jobserver.slots(os.environ.get('MAKEFLAGS'), config['jobs']) as jobs:
        options['jobs'] = jobs
        Release(options).run()
    sets = sorted(destination.glob('release/*/binary/sets'))
    _require(len(sets) == 1, f'{node["id"]}: the OS release has no binary/sets directory')
    return {name: str(sets[0] / name) for name in node['outputs']}


NINJA_MINIMUM = (1, 13)


def ninja_version(ninja):
    try:
        text = subprocess.run([ninja, '--version'], capture_output=True, text=True, check=True,
                              timeout=60).stdout
        return tuple(int(part) for part in re.match(r'(\d+)\.(\d+)', text).groups())
    except (OSError, subprocess.SubprocessError, AttributeError) as exc:
        raise SDKError(f'cannot read the version of {ninja}') from exc


def build(plan, *, work, command, ninja, jobs, explain=False):
    """Write the plan and build.ninja into WORK and run Ninja. Return its status."""
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    with open(work / '.lock', 'a') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise SDKError(f'another profile-build uses {work}') from exc
        pending = [node['id'] for node in plan['nodes'] if node['decision']['action'] != 'ready']
        if not pending:
            write_json(work / PLAN_FILE, plan, exclusive=False)
            print('Build: all nodes are ready; nothing to run.', file=sys.stderr)
            return 0
        text = ninja_file(plan, command=command)
        _require(os.access(ninja, os.X_OK), f'install ninja in the host prefix: {ninja} is missing')
        # Ninja 1.13 and later take their jobs from the jobserver when no -j
        # option is given. Older Ninja would add its own -j budget.
        _require(ninja_version(ninja) >= NINJA_MINIMUM,
                 f'{ninja} is older than Ninja 1.13; install ninja in the host prefix again')
        if any(node['kind'] == 'export' or node['identity'].get('stage') == 'sets'
               for node in plan['nodes'] if node['decision']['action'] != 'ready'):
            _workspace(work, plan, create=True)
        write_json(work / PLAN_FILE, plan, exclusive=False)
        (work / NINJA_FILE).write_text(text + '\n', encoding='utf-8')
        argv = [ninja, '-C', str(work)] + (['-d', 'explain'] if explain else [])
        # The budget replaces the MAKEFLAGS of an outer make: this build has
        # its own jobserver.
        with jobserver.serve(work / '.jobserver', jobs) as makeflags:
            env = dict(os.environ, MAKEFLAGS=makeflags)
            env.pop('MFLAGS', None)
            return subprocess.run(argv, env=env, check=False).returncode
