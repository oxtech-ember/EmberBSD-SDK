"""Build a profile: generate build.ninja from its plan and run each node.

The plan decides what to build. Ninja decides the order and runs the edges.
The producer of a node decides how: a Ports source producer prepares a
source, ember/build-kernel.sh builds the tools and a kernel. Each edge
writes the record of its node (results/<id>.json) after its producer
succeeds. The input key is in the command line of the edge, so Ninja runs an
edge again when the key changes. A node without a key (local changes) depends
on a phony target without outputs, so Ninja runs it on each build; the
incremental builder of its owner then skips unchanged work.
"""

import fcntl
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

from . import build_profile, process
from .errors import SDKError
from .jsonio import read_json, write_json

NINJA_FILE = 'build.ninja'
PLAN_FILE = 'plan.json'
# The OS producers. The tools build runs inside its consumer.
KERNEL_BUILDER = 'ember/build-kernel.sh'


def _require(condition, message):
    if not condition:
        raise SDKError(message)


def _escape(path):
    """Escape a path for a Ninja build line."""
    return str(path).replace('$', '$$').replace(' ', '$ ').replace(':', '$:')


def record_name(node_id):
    return os.path.relpath(build_profile.result_path('/', node_id), '/')


def runnable(node):
    """Return why profile-build cannot run NODE, or None."""
    if node['kind'] == 'source':
        repository, path = node['identity']['producer'].split(':', 1)
        if repository != 'ports' or not path.startswith('scripts/source-inputs/'):
            return f'select the prepared tree in build.sources; profile-build cannot run {repository}:{path} yet'
    elif node['kind'] == 'os-stage' and node['identity'].get('stage') not in ('tools', 'kernel'):
        return 'profile-build builds tools and kernels now; sets follow'
    return None


def ninja_file(plan, *, command):
    """Return build.ninja for the nodes of PLAN that are not ready.

    COMMAND is the argument list that runs one node."""
    nodes = {node['id']: node for node in plan['nodes']}
    # Quote for the shell, then for Ninja. IDs and keys need no quotes.
    command = ' '.join(shlex.quote(str(word)) for word in command).replace('$', '$$')
    lines = ['# Generated by the EmberBSD SDK from the build plan. Do not edit.',
             'ninja_required_version = 1.10', '',
             '# OS stages run build.sh, which runs its own jobs.',
             'pool os', '  depth = 1', '',
             'rule node', f'  command = {command} --node $id --key $key', '  description = $id', '',
             '# A node with local changes depends on this target, which never exists.',
             'build changed: phony', '']
    for node in plan['nodes']:
        if node['decision']['action'] == 'ready':
            continue
        _require(node['decision']['action'] == 'build',
                 f'{node["id"]}: {node["decision"]["action"]} first ({node["decision"]["why"]})')
        reason = runnable(node)
        _require(reason is None, f'{node["id"]}: {reason}')
        # Ready dependencies are already complete; order only the edges of this build.
        inputs = [_escape(record_name(item)) for item in node['dependencies']
                  if nodes[item]['decision']['action'] != 'ready']
        line = f'build {_escape(record_name(node["id"]))}: node'
        if node['input_key'] is None:
            line += ' | changed'
        if inputs:
            line += ' || ' + ' '.join(inputs)
        lines += [line, f'  id = {node["id"]}', f'  key = {node["input_key"] or "changed"}']
        if node['kind'] == 'os-stage':
            lines.append('  pool = os')
        lines.append('')
    return '\n'.join(lines)


def _record(work, node_id):
    path = Path(work, record_name(node_id))
    record = read_json(path) if path.is_file() else None
    _require(isinstance(record, dict) and isinstance(record.get('outputs'), dict),
             f'{node_id} has no result record')
    return record


def _run(argv, env=None):
    # Ninja shows the output of a failed edge.
    if subprocess.run(argv, env=env, check=False).returncode != 0:
        raise SDKError('producer failed: ' + ' '.join(argv[:3]))


def _write_record(work, node, outputs):
    path = Path(work, record_name(node['id']))
    path.parent.mkdir(parents=True, exist_ok=True)
    write_json(path, dict(id=node['id'], input_key=node['input_key'], outputs=outputs), exclusive=False)


def _source_path(work, config, variable):
    selected = config['selected_sources'].get(variable)
    return selected or _record(work, 'source:' + variable)['outputs'][variable]


def run_node(work, node_id, key, config):
    """Run the producer of NODE_ID from the plan in WORK and write its record."""
    plan = read_json(Path(work, PLAN_FILE))
    nodes = {node['id']: node for node in plan['nodes']}
    _require(node_id in nodes, f'the plan has no node {node_id}')
    node = nodes[node_id]
    _require((node['input_key'] or 'changed') == key, f'{node_id}: the plan changed; run profile-build again')
    prefix = config['host_prefix']
    # A producer can remove the outputs of an earlier result, so that result is
    # no longer valid. Remove its record before the producer starts.
    Path(work, record_name(node_id)).unlink(missing_ok=True)
    if node['kind'] == 'source':
        identity = node['identity']
        _require(runnable(node) is None and re.fullmatch(r'EMBER_[A-Z0-9_]+_SOURCE', identity['variable']),
                 f'{node_id}: {runnable(node)}')
        path = identity['producer'].split(':', 1)[1]
        output = Path(work, 'sources', f'{identity["variable"]}-{(node["input_key"] or "changed")[:16]}')
        if output.exists():
            # A failed or interrupted preparation leaves no record; start again.
            shutil.rmtree(output)
        output.parent.mkdir(parents=True, exist_ok=True)
        producer = Path(config['ports_root'], path, 'source.py')
        _run([sys.executable, '-B', str(producer), '--sdk-source', config['sdk_root'],
                     '--git', shutil.which('git') or 'git', 'prepare',
                     '--archive', str(Path(config['distfiles'], identity['archive'])),
                     '--patch', os.path.join(prefix, 'bin/gpatch'), '--output', str(output)])
        _write_record(work, node, {identity['variable']: str(output)})
    elif node_id == 'os:tools':
        # build.sh of each consumer builds or reuses the tools in its object tree.
        _write_record(work, node, {})
    elif node['identity'].get('stage') == 'kernel':
        config_name = node['identity']['config']
        out = Path(work, 'kernels')
        env = process.sanitized_environment()
        env.pop('MAKECONF', None)
        env.update(EMBERBSD_SDK_SOURCE=config['sdk_root'], EMBER_HOST_PREFIX=prefix,
                   EMBER_HOST_COMPILER_FAMILY=plan['profile']['platform']['compiler']['host'],
                   EMBER_COMPILER_FAMILY=plan['profile']['platform']['compiler']['target'],
                   EMBER_BUILD_MODE='cross', EMBER_EXTERNAL_TOOLCHAIN=prefix,
                   EMBER_HOST_BFD_CONFIG=config['host_bfd_config'],
                   MKREPRO_TIMESTAMP=str(node['inputs']['repro_timestamp']),
                   NETBSD2_JOBS=str(config['jobs']))
        if plan['profile']['os']['buildinfo']:
            env['BUILDINFO'] = plan['profile']['os']['buildinfo']
        sources = [item for item in nodes['os:tools']['dependencies'] + node['dependencies']
                   if item.startswith('source:')]
        for item in sorted(set(sources)):
            variable = item.split(':', 1)[1]
            env[variable] = _source_path(work, config, variable)
        out.mkdir(parents=True, exist_ok=True)
        _run([os.path.join(prefix, 'bin/mksh'), os.path.join(config['os_source'], KERNEL_BUILDER),
                     str(out), config_name], env=env)
        _write_record(work, node, {name: str(out / name) for name in node['outputs']})
    else:
        raise SDKError(f'{node_id}: {runnable(node)}')
    return 0


def build(plan, *, work, command, ninja, jobs, explain=False):
    """Write the plan and build.ninja into WORK and run Ninja. Return its status."""
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    with open(work / '.lock', 'a') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise SDKError(f'another profile-build uses {work}') from exc
        pending = [node['id'] for node in plan['nodes'] if node['decision']['action'] != 'ready']
        if not pending:
            write_json(work / PLAN_FILE, plan, exclusive=False)
            print('Build: all nodes are ready; nothing to run.', file=sys.stderr)
            return 0
        text = ninja_file(plan, command=command)
        _require(os.access(ninja, os.X_OK), f'install ninja in the host prefix: {ninja} is missing')
        write_json(work / PLAN_FILE, plan, exclusive=False)
        (work / NINJA_FILE).write_text(text + '\n', encoding='utf-8')
        argv = [ninja, '-C', str(work), '-j', str(jobs)] + (['-d', 'explain'] if explain else [])
        return subprocess.run(argv, check=False).returncode
